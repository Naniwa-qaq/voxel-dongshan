"""Sample existing WorldCover/DSM in the design plane; no source mutation.

This is an ecological art guide, not surveyed grass, species or orchard parcels.
Run with the existing GDAL / NumPy / SciPy Python environment.
"""
from pathlib import Path
import hashlib
import json
import numpy as np
from osgeo import gdal
from scipy.ndimage import gaussian_filter, median_filter

gdal.UseExceptions()
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / '东山镇_重制版'
D = json.loads((OUT / 'data/unified-map.json').read_text(encoding='utf-8'))
paths = [ROOT / '东山镇_数据/landcover/derived/dongshan_envelope_worldcover_2021_v200_utm51n_10m.tif',
         ROOT / '东山镇_数据/terrain/derived/dongshan_envelope_glo30_2021_utm51n_30m.tif']
digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
hashes = {str(p.relative_to(ROOT)): digest(p) for p in paths}
wc_ds, dem_ds = [gdal.Open(str(p)) for p in paths]
wc, wt = wc_ds.ReadAsArray(), wc_ds.GetGeoTransform()
dem = gaussian_filter(median_filter(dem_ds.ReadAsArray().astype(float), size=3), .65)
dt = dem_ds.GetGeoTransform()
dz, dx = np.gradient(dem, abs(dt[5]), dt[1])
slopes = np.hypot(dx, dz)
transform = D['geographic']['designTransform']
ox, oy = D['geographic']['originUTM51N']
b, step = D['bounds'], 10
xs = np.arange(b['minX'], b['maxX'] + step, step)
zs = np.arange(b['minZ'], b['maxZ'] + step, step)
gx = np.interp(xs, transform['designX'], transform['sourceX']) + ox
gy = oy - np.interp(zs, transform['designZ'], transform['sourceZ'])
wx = np.clip(((gx - wt[0]) / wt[1]).astype(int), 0, wc.shape[1] - 1)
wz = np.clip(((gy - wt[3]) / wt[5]).astype(int), 0, wc.shape[0] - 1)
cover = wc[np.ix_(wz, wx)]
ix = np.clip(((gx - dt[0]) / dt[1]).astype(int), 0, dem.shape[1] - 1)
iz = np.clip(((gy - dt[3]) / dt[5]).astype(int), 0, dem.shape[0] - 1)
slope = np.clip(np.rint(slopes[np.ix_(iz, ix)] * 255), 0, 255).astype('uint8')
# Smooth soft ecological probabilities rather than painting 10m class squares.
weights = np.stack([gaussian_filter((cover == 10).astype(float), 1.1),
                    gaussian_filter(np.isin(cover, [20, 30, 40]).astype(float), 1.1),
                    gaussian_filter(np.isin(cover, [50, 60]).astype(float), 1.1),
                    slope / 255], axis=-1)
rgba = np.clip(np.rint(weights * 255), 0, 255).astype('uint8')
data = dict(version='2026-10-23-ecology-1', minX=int(xs[0]), minZ=int(zs[0]),
            step=step, cols=len(xs), rows=len(zs), cover=cover.ravel().tolist(),
            rgba=rgba.ravel().tolist(), sourceSha256=hashes,
            sourcePixelMetres=dict(worldcover=10, dsm=30),
            channels=['forest probability', 'open vegetation probability', 'built/bare probability',
                      'filtered source DSM slope rise/run, clamped 0..1'],
            identity='10m C-domain ecological display guide via inverse G/C; cover 10 is tree cover, not a species or orchard identification; 11m soft display edges; no new survey resolution',
            sources=['ESA WorldCover 2021 v200 / CC BY 4.0', 'Copernicus GLO-30 / existing source license'])
assert all(digest(p) == hashes[str(p.relative_to(ROOT))] for p in paths)
encoded = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
(OUT / 'data/ecology-mask.json').write_text(encoded, encoding='utf-8')
(OUT / 'js/ecology-mask.js').write_text('/* Generated by scripts/build_ecology_mask.py; source rasters read-only. */\nwindow.DSEcologyMask = ' + encoded + ';\n', encoding='utf-8')
print(json.dumps(dict(cols=len(xs), rows=len(zs), classes=np.unique(cover).tolist(), sourceFilesUnchanged=True)))
